"""Refresh the bundled Google documentation catalog. Requires requests and beautifulsoup4."""
import json, re, datetime
from pathlib import Path
import requests
from bs4 import BeautifulSoup

urls = {
    'translate': 'https://ai.google.dev/gemini-api/docs/live-api/live-translate',
    'transcribe': 'https://ai.google.dev/gemini-api/docs/live-api/live-transcribe',
    'live': 'https://ai.google.dev/gemini-api/docs/live-api/capabilities',
    'voices': 'https://ai.google.dev/gemini-api/docs/speech-generation'
}

data = {
    'retrievedAt': datetime.datetime.now(datetime.timezone.utc).isoformat(),
    'sources': urls,
    'languages': {},
    'tones': [
        {'id': '', 'name': 'Natural · preserve original speaker’s tone'},
        {'id': 'calm', 'name': 'Calm and measured (relaxed, soothing)'},
        {'id': 'warm', 'name': 'Warm and friendly (approachable, empathetic)'},
        {'id': 'professional', 'name': 'Professional and clear (authoritative, high-trust)'},
        {'id': 'upbeat', 'name': 'Upbeat and energetic (lively, cheerful)'},
        {'id': 'gentle', 'name': 'Gentle and reassuring (comforting)'},
        {'id': 'serious', 'name': 'Serious and composed (firm, focused)'},
        {'id': 'conversational', 'name': 'Casual and conversational (natural dialogue)'},
        {'id': 'informative', 'name': 'Informative and educational (tutor, explainer)'},
        {'id': 'urgent', 'name': 'Fast-paced and urgent (direct, dynamic)'},
        {'id': 'custom', 'name': 'Custom tone prompt…'}
    ]
}

# Load voice library metadata if available for rich voice attributes
vl_map = {}
vl_path = Path(__file__).resolve().parents[1] / 'app' / 'voice-library.js'
if vl_path.exists():
    try:
        text = vl_path.read_text(encoding='utf-8')
        m = re.search(r'export const voiceLibrary\s*=\s*(\[[\s\S]*\]);', text)
        if m:
            vl = json.loads(m.group(1))
            vl_map = {v['display_name'].lower(): v for v in vl}
    except Exception as e:
        print('Could not load voice library:', e)

for kind, url in urls.items():
    response = requests.get(url, timeout=30)
    response.raise_for_status()
    s = BeautifulSoup(response.text, 'html.parser')
    if kind == 'voices':
        table = s.find(id='prebuilt_voices').find_next('table')
        voices = []
        for c in table.find_all('td'):
            if c.find('b') and c.find('em'):
                name = c.find('b').get_text(strip=True)
                desc = c.find('em').get_text(strip=True)
                meta = vl_map.get(name.lower(), {})
                voices.append({
                    'name': name,
                    'description': desc,
                    'gender': meta.get('gender', ''),
                    'pitch': meta.get('pitch', ''),
                    'persona': meta.get('persona', ''),
                    'details': meta.get('description', '')
                })
        assert len(voices) >= 30
        data['voices'] = voices
    else:
        table = s.find(id='supported-languages').find_next('table')
        items = []
        for row in table.find_all('tr'):
            cells = row.find_all('td')
            for i in range(0, len(cells) - 1, 2):
                name = cells[i].get_text(' ', strip=True)
                for code in cells[i + 1].get_text(' ', strip=True).split(','):
                    code = code.strip()
                    if name and re.fullmatch(r'[a-zA-Z]{2,3}(?:-[a-zA-Z0-9]{2,8})*', code):
                        items.append({'code': code, 'name': name})
        assert len(items) > 70, (kind, len(items))
        data['languages'][kind] = sorted(items, key=lambda x: (x['name'], x['code']))

out = Path(__file__).resolve().parents[1] / 'app' / 'catalog-data.js'
out.write_text('// Generated by scripts/scrape-capabilities.py from Google documentation.\nexport const catalog = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n')
print({k: len(v) for k, v in data['languages'].items()}, 'voices', len(data['voices']))
